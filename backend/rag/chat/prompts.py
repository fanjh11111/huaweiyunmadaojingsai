def is_release_related(text: str) -> bool:
    """判断问题是否涉及放行/适航/安全，需要追加人工复核提示。"""
    keywords = ("放行", "适航", "能否继续", "可以飞", "可以放", "签发", "适航指令", "安全边界")
    lowered = text.lower()
    return any(keyword in lowered for keyword in keywords)


